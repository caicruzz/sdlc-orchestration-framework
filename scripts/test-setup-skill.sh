#!/usr/bin/env bash
# T005 test: the factory-setup skill and its detection reference.
#
# The skill is model-driven, so each scenario is checked by asserting that
# SKILL.md / reference.md carry the instruction or exact message that produces
# the behaviour. Read-only. One function per scenario; each check prints
# "ok <check>" or "FAIL <check>". Exits non-zero if any check fails.
set -euo pipefail
cd "$(dirname "$0")/.."

SKILL_DIR="plugin/skills/factory-setup"
SK="$SKILL_DIR/SKILL.md"
REF="$SKILL_DIR/reference.md"

FAILED=0

ok() { echo "ok   $*"; }
bad() {
  echo "FAIL $*"
  FAILED=1
}

# check <description> <command...>: run a test command, report ok/FAIL.
check() {
  local desc="$1"
  shift
  if "$@"; then ok "$desc"; else bad "$desc"; fi
}

# has <file> <fixed string>: the file contains the string on one line.
has() { [ -f "$1" ] && grep -qF -- "$2" "$1"; }

# in_skill / in_ref <phrase>: report whether SKILL.md / reference.md has it.
in_skill() { check "SKILL.md: $1" has "$SK" "$1"; }
in_ref() { check "reference.md: $1" has "$REF" "$1"; }

# frontmatter: the YAML between the first two "---" lines of SKILL.md, joined
# into one line with runs of whitespace collapsed (folded descriptions wrap).
frontmatter() {
  [ -f "$SK" ] || return 0
  awk 'NR == 1 && $0 != "---" { exit } NR > 1 && $0 == "---" { exit } NR > 1 { print }' "$SK" |
    tr '\n' ' ' | tr -s ' \t' ' '
}

fm_has() { frontmatter | grep -qF -- "$1"; }

# Scenario: Frontmatter
scenario_frontmatter() {
  echo "# Frontmatter"
  local lines t
  check "SKILL.md exists" test -f "$SK"
  check "reference.md exists next to SKILL.md" test -f "$REF"
  check "frontmatter has name: factory-setup" fm_has "name: factory-setup"
  check "frontmatter description is folded (>-)" fm_has "description: >-"
  for t in "set up the factory" "onboard this repo to soloAIfactory" \
    "configure soloAIfactory" "create .ai-factory/config.md" "/factory-setup"; do
    check "description names trigger: $t" fm_has "$t"
  done
  lines=$( (wc -l <"$SK" 2>/dev/null || echo 9999) | tr -d ' ')
  if [ "$lines" -lt 500 ]; then ok "SKILL.md is under 500 lines ($lines)"; else bad "SKILL.md is under 500 lines ($lines)"; fi
  in_skill "Read [\`reference.md\`](reference.md)"
  in_skill "for the detection heuristics"
  in_skill "## When to use"
  in_skill "## What you must not do"
  in_skill "## Verification (for the agent)"
  local step
  for step in "### 1. Resolve the root" "### 2. Read existing state" \
    "### 3. If set up, report and stop" "### 4. Inspect" \
    "### 5. Show the proposal" "### 6. Write" "### 7. Optional smoke run" \
    "### 8. Hand off"; do
    in_skill "$step"
  done
}

