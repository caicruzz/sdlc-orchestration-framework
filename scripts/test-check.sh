# Scenario: Frozen labels
scenario_frozen_labels() {
  echo "# Frozen labels"
  local frozen="FAIL frozen config Commands labels"
  new_case
  edit "$CONFIG_TEMPLATE" 's#^| \*\*Format\*\* |#| **Formatting** |#'
  expect_fail "label renamed" "$frozen" "$CONFIG_TEMPLATE" "Formatting"

  new_case
  edit "$CONFIG_TEMPLATE" '/^| \*\*Install\*\* |/d'
  expect_fail "label removed" "$frozen" "$CONFIG_TEMPLATE"

  new_case
  awk '/^\| \*\*Type check\*\* \|/ { held = $0; next } { print } /^\| \*\*Build\*\* \|/ { print held }' \
    "$CASE/$CONFIG_TEMPLATE" >"$tmp/edit"
  cat "$tmp/edit" >"$CASE/$CONFIG_TEMPLATE"
  expect_fail "labels reordered" "$frozen" "$CONFIG_TEMPLATE"

  new_case
  edit "$CONFIG_TEMPLATE" 's#^\(| \*\*Lint\*\* |.*| \)Required |$#\1Optional |#'
  expect_fail "Lint no longer Required" "$frozen" "$CONFIG_TEMPLATE"

  new_case
  edit "$CONFIG_TEMPLATE" 's#^\(| \*\*Build\*\* |.*| \)Optional — remove if not applicable |$#\1Required |#'
  expect_fail "Build made Required" "$frozen" "$CONFIG_TEMPLATE"
}

# --- Scenarios: repository rules --------------------------------------------

# Scenario: Installer mode
scenario_installer_mode() {
  echo "# Installer mode"
  new_case
  chmod -x "$CASE/install.sh"
  git -C "$CASE" update-index --chmod=-x install.sh
  expect_fail "install.sh not executable" "install.sh is tracked with mode 100644"

  new_case
  git -C "$CASE" rm -q --cached install.sh
  git_test -C "$CASE" commit -qm untrack
  run_check "$CASE"
  check "install.sh untracked: check.sh exits non-zero" nonzero
  check "install.sh untracked: output names install.sh" has "install.sh is not tracked"
}

# Scenario: No tracked tool directories
scenario_no_tracked_tool_dirs() {
  echo "# No tracked tool directories"
  new_case
  mkdir -p "$CASE/.claude" "$CASE/.cursor/rules"
  printf '{}\n' >"$CASE/.claude/settings.json"
  printf 'rule\n' >"$CASE/.cursor/rules/x.mdc"
  git -C "$CASE" add -f .claude/settings.json .cursor/rules/x.mdc
  expect_fail "tracked tool directories" ".claude/settings.json" ".cursor/rules/x.mdc"
}

