# Scenario: Read-only tools are safe
scenario_read_only_tools_are_safe() {
  echo "# Read-only tools are safe"
  local tool
  for tool in Edit Write; do
    new_case
    edit plugin/agents/factory-evaluator.md "s/^tools: Read, Grep, Glob$/tools: Read, Grep, Glob, $tool/"
    expect_fail "read-only agent with $tool" "plugin/agents/factory-evaluator.md: read-only agent has tool $tool"
  done

  new_case
  edit plugin/agents/factory-evaluator.md 's/^tools: Read, Grep, Glob$/tools: Read, Grep, Glob, Bash/'
  expect_fail "evaluator with Bash" "plugin/agents/factory-evaluator.md: only factory-reviewer and factory-verifier may have tool Bash"

  new_case
  insert_after plugin/agents/factory-planner.md "model: inherit" "readonly: true"
  insert_after plugin/agents/factory-planner.md "readonly: true" "tools: Read, Bash"
  expect_fail "planner with Bash" "plugin/agents/factory-planner.md: only factory-reviewer and factory-verifier may have tool Bash"
}

# --- Scenarios: stale paths -------------------------------------------------

# Scenario: Retired paths in tracked files
scenario_retired_paths() {
  echo "# Retired paths in tracked files"
  local l1 l2 l3 l4
  new_case
  append README.md "Copy $STALE_TEMPLATES/design.md first."
  l1=$(lines README.md)
  append plugin/skills/factory-plan/SKILL.md "Read $STALE_FRAMEWORK/agents."
  l2=$(lines plugin/skills/factory-plan/SKILL.md)
  append examples/oauth2/00-design.md "See $STALE_EXAMPLES/oauth2."
  l3=$(lines examples/oauth2/00-design.md)
  append plugin/agents/factory-coder.md "Run $STALE_SYNC after editing."
  l4=$(lines plugin/agents/factory-coder.md)
  # Excluded: test scripts may name retired paths.
  append scripts/test-readme.sh "# $STALE_TEMPLATES"
  expect_fail "retired paths" \
    "README.md:$l1" \
    "plugin/skills/factory-plan/SKILL.md:$l2" \
    "examples/oauth2/00-design.md:$l3" \
    "plugin/agents/factory-coder.md:$l4"
  check "excluded scripts/test-*.sh is not reported" lacks_out "scripts/test-readme.sh"
}

