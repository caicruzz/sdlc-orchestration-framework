#!/usr/bin/env bash
# T010 tests: scripts/check.sh accepts this repository and every rule fires.
#
# Isolation: the repository's tracked and untracked-but-not-ignored files are
# copied once into a fresh git repository under ${TMPDIR:-/tmp} (the base
# copy). Each negative case copies the base, plants one violation, commits it
# and runs that copy's scripts/check.sh, asserting a non-zero exit and that the
# output names the violation. The real repository is never written; its git
# status is compared at start and end.
#
# One function per scenario; each check prints "ok <check>" or "FAIL <check>".
# Exits non-zero if any check fails. bash 3.2 compatible.
set -euo pipefail

repo="$(cd "$(dirname "$0")/.." && pwd -P)"

tmp_root="${TMPDIR:-/tmp}"
tmp_root="${tmp_root%/}"
if [ -z "$tmp_root" ] || [ ! -d "$tmp_root" ]; then
  echo "abort: temporary directory ${TMPDIR:-/tmp} is not usable" >&2
  exit 1
fi

FAILED=0
ok() { echo "ok   $*"; }
bad() {
  echo "FAIL $*"
  FAILED=1
}
check() {
  local desc="$1"
  shift
  if "$@"; then ok "$desc"; else bad "$desc"; fi
}

repo_state() {
  git -C "$repo" rev-parse HEAD
  git -C "$repo" status --porcelain --untracked-files=all
}
real_state_start="$(repo_state)"

# Retired paths, built by concatenation so this file never names them literally.
AF=".ai-factory"
STALE_TEMPLATES="$AF/templates"
STALE_FRAMEWORK="$AF/framework"
STALE_EXAMPLES="$AF/examples"
STALE_SYNC="sync"
STALE_SYNC="$STALE_SYNC.sh"
MARKER="Generated by $AF/$STALE_SYNC"

VERIFIER="plugin/agents/factory-verifier.md"
BUILD="plugin/skills/factory-build/SKILL.md"
CONFIG_TEMPLATE="plugin/skills/factory-setup/templates/config.md"

# --- Temporary workspace and the base copy ----------------------------------

tmp="$(mktemp -d "$tmp_root/sif-check.XXXXXX")"
case "$tmp" in
"$tmp_root"/sif-check.*) ;;
*)
  echo "abort: temporary directory $tmp is not under $tmp_root" >&2
  exit 1
  ;;
esac
cleanup() { rm -rf -- "$tmp"; }
trap cleanup EXIT

git_test() {
  git -c user.name=test -c user.email=test@example.invalid -c commit.gpgsign=false \
    -c core.hooksPath=/dev/null "$@"
}

base="$tmp/base"
mkdir "$base"
(cd "$repo" && git ls-files -z --cached --others --exclude-standard) >"$tmp/files"
while IFS= read -r -d '' f; do
  case "$f" in */) continue ;; esac # nested repositories (e.g. worktrees)
  if [ ! -f "$repo/$f" ] && [ ! -L "$repo/$f" ]; then continue; fi # deleted from the working tree
  mkdir -p "$base/$(dirname "$f")"
  cp -pR "$repo/$f" "$base/$f"
done <"$tmp/files"
git -C "$base" init -q
git -C "$base" add -A
git_test -C "$base" commit -qm fixture
base="$(cd "$base" && pwd -P)"

# --- Helpers ----------------------------------------------------------------

CASE_N=0
# new_case: copy the base into a fresh case directory; sets CASE.
new_case() {
  CASE_N=$((CASE_N + 1))
  CASE="$tmp/case-$CASE_N"
  cp -pR "$base" "$CASE"
}

# commit_case: stage everything in the case and commit it.
commit_case() {
  git -C "$CASE" add -A
  git_test -C "$CASE" commit -qm plant
}

# edit <relative file> <sed expression>: edit a file in the case in place
# (portable: no sed -i), keeping its mode.
edit() {
  local f="$CASE/$1"
  sed "$2" "$f" >"$tmp/edit"
  cat "$tmp/edit" >"$f"
  cmp -s "$tmp/edit" "$base/$1" && {
    echo "abort: edit of $1 changed nothing ($2)" >&2
    exit 1
  }
  return 0
}

# append <relative file> <line>
append() { printf '%s\n' "$2" >>"$CASE/$1"; }

# insert_after <relative file> <exact line> <new line>
insert_after() {
  local f="$CASE/$1"
  awk -v a="$2" -v n="$3" '{ print } $0 == a && !done { print n; done = 1 }' "$f" >"$tmp/edit"
  cat "$tmp/edit" >"$f"
}

# lines <relative file>: number of lines in a case file.
lines() { awk 'END { print NR }' "$CASE/$1"; }

# run_check <repo dir> [cwd]: run that copy's check.sh; sets OUT and RC.
run_check() {
  local dir="$1" cwd="${2:-$1}"
  RC=0
  OUT="$(cd "$cwd" && "$BASH" "$dir/scripts/check.sh" 2>&1)" || RC=$?
}

has() { printf '%s\n' "$OUT" | grep -qF -- "$1"; }
lacks_out() { ! has "$1"; }
nonzero() { [ "$RC" -ne 0 ]; }

# expect_fail <desc> <needle...>: commit the planted case, run its check.sh
# and assert a non-zero exit and that every needle is in the output.
expect_fail() {
  local desc="$1" n
  shift
  commit_case
  run_check "$CASE"
  if nonzero; then ok "$desc: check.sh exits non-zero"; else bad "$desc: check.sh exits non-zero (output: $OUT)"; fi
  for n in "$@"; do
    if has "$n"; then ok "$desc: output names '$n'"; else bad "$desc: output names '$n' (output: $OUT)"; fi
  done
}

# --- Scenarios: check.sh passes on this repository ----------------------------

# Scenario: Clean repository
scenario_clean_repository() {
  echo "# Clean repository"
  local n
  run_check "$base"
  check "unmodified copy: check.sh exits 0 with $BASH" test "$RC" -eq 0
  [ "$RC" -eq 0 ] || echo "$OUT"
  n=$(printf '%s\n' "$OUT" | grep -c '^ok   ' || true)
  check "unmodified copy: one ok line per rule group (10, found $n)" test "$n" -eq 10
  check "unmodified copy: no FAIL lines" lacks_out "FAIL"
  if [ -x /bin/bash ]; then
    RC=0
    OUT="$(cd "$base" && /bin/bash "$base/scripts/check.sh" 2>&1)" || RC=$?
    check "unmodified copy: check.sh exits 0 with /bin/bash" test "$RC" -eq 0
  fi
  run_check "$repo"
  check "this repository: check.sh exits 0" test "$RC" -eq 0
  [ "$RC" -eq 0 ] || echo "$OUT"
}

# Scenario: check.sh works from any current directory
scenario_any_current_directory() {
  echo "# check.sh works from any current directory"
  run_check "$base" "$tmp"
  check "run from outside any repository: exits 0" test "$RC" -eq 0
  run_check "$base" /
  check "run from /: exits 0" test "$RC" -eq 0
  # From inside a broken copy, the clean copy's script still checks its own
  # repository.
  new_case
  edit "$VERIFIER" 's/^name: factory-verifier$/name: wrong/'
  commit_case
  run_check "$base" "$CASE"
  check "run from inside another (broken) repository: exits 0" test "$RC" -eq 0
}

