  check "README.md is not reported" lacks_out "README.md:"
}

# --- Scenarios: Verifier contract -------------------------------------------

# Scenario: Verifier labels and Required flags match the config template
scenario_verifier_labels_and_required() {
  echo "# Verifier labels and Required flags match the config template"
  new_case
  edit "$VERIFIER" 's#^| Lint | \*\*Lint\*\* | Yes |$#| Lint | **Linter** | Yes |#'
  expect_fail "Verifier label not in Commands" "$VERIFIER: label **Linter** is not a Commands label"

  new_case
  edit "$VERIFIER" 's#^| Type check | \*\*Type check\*\* | No |$#| Type check | **Type check** | Yes |#'
  expect_fail "optional row marked Required" "$VERIFIER: **Type check** is not Required"

  new_case
  edit "$VERIFIER" 's#^| Tests | \*\*Test\*\* | Yes |$#| Tests | **Test** | No |#'
  expect_fail "Required row marked No" "$VERIFIER: **Test** is Required"
}

