#!/usr/bin/env bash
# T009 README test: the README documents the install-and-onboard flow.
#
# Read-only. One function per scenario; each check prints "ok <check>" or
# "FAIL <check>". Exits non-zero if any check fails. Only lasting results are
# asserted (what README.md says), never the diff that produced it.
#
# The retired paths are built from pieces below so this file never contains
# them literally (a repository check greps tracked files for them).
# shellcheck disable=SC2016,SC2088 # backticks and tildes are literal Markdown
set -euo pipefail
cd "$(dirname "$0")/.."

README=README.md
FAILED=0

ok() { echo "ok   $*"; }
bad() {
  echo "FAIL $*"
  FAILED=1
}

AF=".ai-factory"
GEN="sync"".sh"
MARKER="Generated by $AF/$GEN"

# section <title>: the lines of "## <title>" up to the next level-2 heading.
section() {
  awk -v h="## $1" '
    $0 == h { f = 1; print; next }
    f && /^## / { exit }
    f { print }
  ' "$README"
}

# subsection <title>: the lines of "### <title>" up to the next heading of
# level 1 to 3.
subsection() {
  awk -v h="### $1" '
    $0 == h { f = 1; next }
    f && (/^### / || /^## / || /^# /) { exit }
    f { print }
  ' "$README"
}

# has <text> <needle> <description>: <text> contains <needle> (fixed string).
has() {
  if printf '%s\n' "$1" | grep -qF -- "$2"; then ok "$3"; else bad "$3"; fi
}

# has_i: like has, ignoring case.
has_i() {
  if printf '%s\n' "$1" | grep -qiF -- "$2"; then ok "$3"; else bad "$3"; fi
}

# lacks <text> <needle> <description>: <text> does not contain <needle>.
lacks() {
  if printf '%s\n' "$1" | grep -qF -- "$2"; then bad "$3"; else ok "$3"; fi
}

# fenced_alone <text> <line> <description>: <line> appears in <text> as the
# only line of a ```bash code block.
fenced_alone() {
  if printf '%s\n' "$1" | awk -v x="$2" '
    { a[NR] = $0 }
    END {
      found = 0
      for (i = 2; i < NR; i++)
        if (a[i] == x && a[i - 1] == "```bash" && a[i + 1] == "```") found = 1
      exit found ? 0 : 1
    }'; then
    ok "$3"
  else
    bad "$3"
  fi
}

# heading_line <exact heading line>: its line number in the README, or 0.
heading_line() {
  local n
  n=$(grep -n -x -F -- "$1" "$README" | head -n 1 | cut -d: -f1 || true)
  printf '%s' "${n:-0}"
}

# readme_links: every [label](target) target in the README, one per line.
readme_links() {
  grep -o '](\([^)]*\))' "$README" | sed 's/^](//; s/)$//' || true
}

# heading_slugs: the GitHub anchor of every heading outside code blocks.
heading_slugs() {
  awk '
    /^ *```/ { code = !code; next }
    !code && /^#+ / { sub(/^#+ /, ""); print }
  ' "$README" | tr '[:upper:]' '[:lower:]' | sed 's/[^a-z0-9 _-]//g; s/ /-/g'
}

