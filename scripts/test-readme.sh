# Scenario: Stage-skill links stay repointed
scenario_stage_skill_links() {
  echo "# Stage-skill links stay repointed"
  local links t path skill bad_links want slugs
  links=$(readme_links)
  # Every link labelled with a stage skill points at that skill's SKILL.md.
  bad_links=$(grep -o '\[`factory-[a-z]*`\]([^)]*)' "$README" | while IFS= read -r t; do
    skill=${t#\[\`}
    skill=${skill%%\`*}
    path=${t#*](}
    path=${path%)}
    if [ "$path" != "plugin/skills/$skill/SKILL.md" ]; then printf '%s\n' "$t"; fi
  done || true)
  if [ -z "$bad_links" ]; then
    ok "every stage-skill link targets plugin/skills/<skill>/SKILL.md"
  else
    bad "every stage-skill link targets plugin/skills/<skill>/SKILL.md (found: $bad_links)"
  fi
  for want in \
    plugin/skills/factory-setup/SKILL.md \
    plugin/skills/factory-design/SKILL.md \
    plugin/skills/factory-plan/SKILL.md \
    plugin/skills/factory-build/SKILL.md \
    plugin/skills/factory-archive/SKILL.md \
    plugin/skills/factory-archive/reference.md; do
    if printf '%s\n' "$links" | grep -qxF -- "$want"; then
      ok "README links to $want"
    else
      bad "README links to $want"
    fi
  done
  # Every relative link resolves; every in-page anchor names a heading.
  slugs=$(heading_slugs)
  while IFS= read -r t; do
    [ -n "$t" ] || continue
    case "$t" in
      http://* | https://* | mailto:*) continue ;;
      \#*)
        if printf '%s\n' "$slugs" | grep -qxF -- "${t#\#}"; then
          ok "anchor $t names a heading"
        else
          bad "anchor $t names a heading"
        fi
        ;;
      *)
        path=${t%%#*}
        if [ -e "$path" ]; then ok "link $path resolves"; else bad "link $path resolves"; fi
        ;;
    esac
  done <<EOF
$links
EOF
}

# tree_entry <tree> <entry> [<comment>] <description>: some line of <tree>,
# with its "# ..." comment and trailing blanks removed, is exactly <entry>
# (indentation included), and, when <comment> is not empty, that line's
# comment contains <comment>.
tree_entry() {
  if printf '%s\n' "$1" | awk -v e="$2" -v c="$3" '
    {
      name = $0; com = ""
      i = index($0, "#")
      if (i > 0) { name = substr($0, 1, i - 1); com = substr($0, i + 1) }
      sub(/[ \t]+$/, "", name)
      if (name == e && (c == "" || index(com, c) > 0)) found = 1
    }
    END { exit found ? 0 : 1 }'; then
    ok "$4"
  else
    bad "$4"
  fi
}

